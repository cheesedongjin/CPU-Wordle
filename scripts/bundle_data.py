"""Bundle local dictionaries for file:// and static hosting (no fetch required)."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
data = {lang: {kind: (ROOT / f"data/{lang}_{kind}.txt").read_text(encoding="utf-8").splitlines()
               for kind in ["answers", "allowed"]} for lang in ["ko", "en"]}
(ROOT / "web/words.js").write_text("// Generated by scripts/bundle_data.py; see data/README.md for licenses.\nconst WORDLE_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
